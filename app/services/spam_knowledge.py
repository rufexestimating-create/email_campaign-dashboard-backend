def builtin_keywords() -> list[dict]:
    # A phrase listed in more than one category is kept once (first category wins) so it never scores twice
    seen: set[str] = set()
    out = []
    for c in CATEGORIES:
        for phrase, severity, alternative in c["keywords"]:
            if phrase in seen:
                continue
            seen.add(phrase)
            out.append({"phrase": phrase, "severity": severity, "alternative": alternative, "category": c["id"], "category_name": c["name"], "why": c["why"], "source": "builtin"})
    return out
